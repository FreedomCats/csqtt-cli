package datapath

import "net/netip"

// TunnelMTU — MTU туннеля, как у адаптера Android-клиента CSQTT.
const TunnelMTU = 1300

// TunConf — что сервер выдал строкой TUNCONF: адрес туннеля и DNS.
type TunConf struct {
	Address netip.Addr
	DNS     []netip.Addr
}

// Requirements — условия, на которых datapath может работать. Пустое значение
// — «ничего не нужно»: так выглядит socks, работающий от обычного
// пользователя.
type Requirements struct {
	// Unsupported — почему datapath не работает на этой системе; nil —
	// работает. Если задано, остальные поля вызывающий не проверяет: права
	// для того, что всё равно не запустится, советовать незачем.
	Unsupported error

	// Admin — нужны права администратора (root). Проверяет их вызывающий:
	// сам datapath о правах процесса ничего не знает.
	Admin bool

	// Netguard — datapath забирает весь трафик системы, и собственные сокеты
	// ядра нужно увести мимо туннеля (привязка к физическому интерфейсу,
	// П3), иначе туннель зависит от самого себя (architecture.md §06).
	Netguard bool

	// DNSGuard — datapath ставит правила защиты от утечки DNS и ждёт их
	// сессию в своих опциях (TunOptions.DNSGuard). Открывает её вызывающий,
	// до подключения: отказ nftables — понятная ошибка сразу, а не цикл
	// переподключений.
	DNSGuard bool
}

// DNSGuard — защита от утечки DNS, общая на весь csqtt-cli connect (на
// Linux — linuxsys.DNSGuard). Datapath включает её, когда маршруты стоят,
// переключает на новые резолверы при смене DNS на ходу и снимает в Suspend
// и Close; оба вызова безвредны повторно.
type DNSGuard interface {
	// Enable пускает DNS только к резолверам dns (и запросы самого
	// csqtt-cli); повторный вызов заменяет прежний список.
	Enable(dns []netip.Addr) error
	// Disable снимает запрет.
	Disable() error
}

// IPv6Blocker — необязательная часть DNSGuard (Linux): защита, которая
// умеет заодно закрыть IPv6 системы наружу. Туннель CSQTT IPv6 не везёт, и на
// Linux, где пакеты идут в ядро мимо оболочки, отбросить их некому — без
// запрета IPv6 шёл бы мимо туннеля. Локальная сеть IPv6 остаётся открытой.
type IPv6Blocker interface {
	// BlockIPv6 задаёт, закрывать ли IPv6 наружу при следующем Enable.
	BlockIPv6(block bool)
}

// Reserver — необязательная часть datapath: реализация, которой до
// подключения нужно занять что-то общее на машину (у tun — адаптер).
// Вызывающий зовёт Reserve до первой попытки и держит резерв весь сеанс:
// отказ здесь — понятная ошибка до похода в VK, а не сбой попытки, который
// супервизор принял бы за повод переподключиться.
type Reserver interface {
	Reserve() (release func(), err error)
}

// Persistent — необязательная часть datapath: реализация, которая живёт весь
// csqtt-cli connect, а не одну попытку. У tun это адаптер: пересоздавать его
// на каждое переподключение незачем, а Windows ещё и заводила бы «Сеть 2»,
// «Сеть 3».
//
// Start такой реализации зовётся на каждую попытку и перенастраивает её
// под новый TUNCONF, а не отказывает «уже запущен».
type Persistent interface {
	// Suspend снимает то, из-за чего трафик системы идёт в туннель, —
	// маршруты, DNS системы и запрет утечки DNS, — и оставляет остальное.
	// Вернёт их следующий успешный Start.
	//
	// Супервизор зовёт его сразу после неудачной попытки, до задержки: пока
	// маршруты ведут в туннель без ядра, страница капчи VK не загрузится, а
	// капчу ядро просит как раз при переподключении. Безвреден до Start и
	// повторно.
	Suspend() error
}
