func readFile(t *testing.T, path string) string {
	t.Helper()
	b, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	return string(b)
}

func exists(path string) bool {
	_, err := os.Lstat(path)
	return err == nil
}

// Перезапись: копия прежнего, свой файл с search и options прежнего,
// повторный Set копию не трогает, Revert возвращает прежний.
func TestSystemDNSFile(t *testing.T) {
	etc, _ := fakeDNSRoots(t)
	path := filepath.Join(etc, "resolv.conf")
	orig := "# от DHCP\nnameserver 192.0.2.1\nsearch example.net\noptions ndots:2\n"
	writeFile(t, path, orig)
	if err := os.Chmod(path, 0o640); err != nil {
		t.Fatal(err)
	}

	dns, err := DetectSystemDNS("csqtt-cli")
	if err != nil {
		t.Fatal(err)
	}
	if done, err := dns.Recover(); err != nil || done != "" {
		t.Fatalf("Recover на чистой системе: %q, %v", done, err)
	}
	if err := dns.Revert(1); err != nil {
		t.Fatalf("Revert до Set: %v", err)
	}
	if got := readFile(t, path); got != orig {
		t.Fatalf("Revert до Set тронул файл: %q", got)
	}

	if err := dns.Set(1, testServers); err != nil {
		t.Fatal(err)
	}
	got := readFile(t, path)
	want := fileMarker + "; прежний файл — resolv.conf.csqtt-cli-backup, csqtt-cli вернёт его при выходе\n" +
		"nameserver 192.0.2.53\nnameserver 2001:db8::53\nsearch example.net\noptions ndots:2\n"
	if got != want {
		t.Errorf("свой файл:\n%s\nждали:\n%s", got, want)
	}
	if b := readFile(t, path+".csqtt-cli-backup"); b != orig {
		t.Errorf("копия: %q", b)
	}
	if fi, _ := os.Stat(path); fi.Mode().Perm() != 0o640 {
		t.Errorf("права %v, ждали 0640", fi.Mode().Perm())
	}
	if !dns.Applied() {
		t.Error("Applied после Set = false")
	}

	// Новый сервер DNS — новый файл, копия та же.
	if err := dns.Set(1, testServers[:1]); err != nil {
		t.Fatal(err)
	}
	if got := readFile(t, path); !strings.Contains(got, "nameserver 192.0.2.53\nsearch") {
		t.Errorf("после повторного Set:\n%s", got)
	}
	if b := readFile(t, path+".csqtt-cli-backup"); b != orig {
		t.Errorf("повторный Set переписал копию: %q", b)
	}

	if err := dns.Revert(1); err != nil {
		t.Fatal(err)
	}
	if got := readFile(t, path); got != orig {
		t.Errorf("после Revert: %q", got)
	}
	if exists(path + ".csqtt-cli-backup") {
		t.Error("копия осталась после Revert")
	}
	if err := dns.Revert(1); err != nil {
		t.Errorf("повторный Revert: %v", err)
	}
	entries, _ := os.ReadDir(etc)
	if len(entries) != 1 {
		t.Errorf("в /etc лишние файлы: %v", entries)
	}
}

