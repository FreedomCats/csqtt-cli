// Обычный файл, который пишет чужая программа, — перезапись с
// предупреждением; файл docker — без него.
func TestSystemDNSFileWarning(t *testing.T) {
	for _, tc := range []struct{ conf, want string }{
		{"# Generated by NetworkManager\nnameserver 192.0.2.1\n", "resolv.conf пишет NetworkManager:"},
		{"# Generated by Docker Engine.\nnameserver 192.0.2.1\n", ""},
		{"nameserver 192.0.2.1\n", ""},
	} {
		etc, _ := fakeDNSRoots(t)
		writeFile(t, filepath.Join(etc, "resolv.conf"), tc.conf)
		dns, err := DetectSystemDNS("csqtt-cli")
		if err != nil {
			t.Fatal(err)
		}
		if dns.Method() != DNSFile || !strings.HasPrefix(dns.Warning(), tc.want) || (tc.want == "") != (dns.Warning() == "") {
			t.Errorf("%q: способ %v, предупреждение %q", tc.conf, dns.Method(), dns.Warning())
		}
	}
}
