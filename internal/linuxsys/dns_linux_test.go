// Остатки упавшего запуска: свой файл и копия — прежний возвращается;
// копия при чужом файле — удаляется.
func TestSystemDNSFileRecover(t *testing.T) {
	etc, _ := fakeDNSRoots(t)
	path := filepath.Join(etc, "resolv.conf")
	orig := "nameserver 192.0.2.1\n"
	writeFile(t, path, orig)
	crashed, _ := DetectSystemDNS("csqtt-cli")
	if err := crashed.Set(1, testServers); err != nil {
		t.Fatal(err)
	}
	// kill -9: Revert не было.

	dns, err := DetectSystemDNS("csqtt-cli")
	if err != nil {
		t.Fatal(err)
	}
	done, err := dns.Recover()
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(done, "возвращён") {
		t.Errorf("Recover: %q", done)
	}
	if got := readFile(t, path); got != orig || exists(path+".csqtt-cli-backup") {
		t.Errorf("после Recover: %q, копия есть: %v", got, exists(path+".csqtt-cli-backup"))
	}

	writeFile(t, path+".csqtt-cli-backup", "nameserver 203.0.113.1\n")
	done, err = dns.Recover()
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(done, "переписал кто-то другой") || readFile(t, path) != orig || exists(path+".csqtt-cli-backup") {
		t.Errorf("Recover при чужом файле: %q, файл %q", done, readFile(t, path))
	}
}

