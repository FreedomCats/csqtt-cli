func TestSystemDNSResolved(t *testing.T) {
	etc, _ := fakeDNSRoots(t)
	writeFile(t, filepath.Join(etc, "resolv.conf"), "nameserver 127.0.0.53\n")
	bus := &fakeBus{}
	stubBus(t, bus, nil)
	dns, err := DetectSystemDNS("csqtt-cli")
	if err != nil {
		t.Fatal(err)
	}
	if done, err := dns.Recover(); err != nil || done != "" {
		t.Fatalf("Recover: %q, %v", done, err)
	}
	bus.calls, bus.args = nil, nil
	if err := dns.Set(7, testServers); err != nil {
		t.Fatal(err)
	}
	if err := dns.Revert(7); err != nil {
		t.Fatal(err)
	}
	if want := []string{"SetLinkDNS", "SetLinkDomains", "SetLinkDefaultRoute", "RevertLink"}; !slices.Equal(bus.calls, want) {
		t.Errorf("вызовы %v, ждали %v", bus.calls, want)
	}
	if bus.closed != 3 { // Ping, Set, Revert
		t.Errorf("соединений закрыто %d", bus.closed)
	}
	wantAddrs := []resolvedAddr{{2, []byte{192, 0, 2, 53}}, {10, testServers[1].AsSlice()}}
	if got := bus.args[0]; got[0] != int32(7) || !slices.EqualFunc(got[1].([]resolvedAddr), wantAddrs, func(a, b resolvedAddr) bool {
		return a.Family == b.Family && slices.Equal(a.Address, b.Address)
	}) {
		t.Errorf("SetLinkDNS%v", got)
	}
	if got := bus.args[1]; !slices.Equal(got[1].([]resolvedDomain), []resolvedDomain{{".", true}}) {
		t.Errorf("SetLinkDomains%v", got)
	}
}

