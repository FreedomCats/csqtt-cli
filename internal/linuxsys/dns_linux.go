// DNS туннеля в системе. На Windows DNS — свойство адаптера
// (winsys.SetAdapterDNS), на Linux единого способа нет: кто ведёт
// /etc/resolv.conf, тот и задаёт DNS системы. csqtt-cli узнаёт его по самому файлу.
//
//   - systemd-resolved — файл ведёт в /run/systemd/resolve или называет его
//     заглушку 127.0.0.53. DNS ставится на линк csqtt-cli по D-Bus с маршрутным
//     доменом «~.» и уходит вместе с линком — уборка не нужна.
//   - resolvconf — файл ведёт в /run/resolvconf (Debian) или написан им
//     (openresolv пишет обычный файл с заголовком «Generated by resolvconf»). Запись tun.<адаптер>: префикс
//     tun ставит её первой (interface-order). Debian resolvconf монопольного
//     режима не знает, и серверы сети остаются в файле после наших — их
//     запросы отбрасывает защита DNS (DNSGuard). openresolv — с -m 0 -x, как
//     wg-quick: в файле только наши.
//   - Перезапись — обычный файл, которого никто не ведёт (контейнер): копия
//     в resolv.conf.csqtt-cli-backup, свой файл с меткой, возврат копии при выходе.
//
// После падения csqtt-cli (kill -9) запись resolvconf и перезаписанный файл
// остаются; их убирает Recover следующего запуска.

// DNSMethod — способ, которым csqtt-cli задаёт DNS системы.
type DNSMethod int

const (
	DNSResolved DNSMethod = iota + 1
	DNSResolvconfDebian
	DNSOpenresolv
	DNSFile
)

func (m DNSMethod) String() string {
	switch m {
	case DNSResolved:
		return "systemd-resolved"
	case DNSResolvconfDebian:
		return "resolvconf (Debian)"
	case DNSOpenresolv:
		return "openresolv"
	case DNSFile:
		return "перезапись /etc/resolv.conf"
	default:
		return fmt.Sprintf("DNSMethod(%d)", int(m))
	}
}

// runRoot — корень /run; подменяется в тестах (как etcRoot).
var runRoot = "/run"

// resolvedStub — адрес заглушки systemd-resolved в resolv.conf.
const resolvedStub = "127.0.0.53"

// resolvconfHeader — заголовок файла, который пишет openresolv.
const resolvconfHeader = "# Generated by resolvconf"

// fileMarker — первая строка resolv.conf, который написал csqtt-cli: по ней
// Recover и Revert отличают свой файл от записанного кем-то после.
const fileMarker = "# " + app.Name + ": DNS туннеля"

// backupSuffix — копия прежнего resolv.conf рядом с ним.
const backupSuffix = "." + app.Name + "-backup"

// SystemDNS — DNS туннеля в системе для адаптера с именем name.
// Не потокобезопасен: зовёт его одна горутина адаптера.
type SystemDNS struct {
	method DNSMethod
	name   string
	// resolvconf — путь к программе resolvconf (Debian и openresolv).
	resolvconf string
	// warning — чем способ ненадёжен (Warning).
	warning string
	// applied — Set звали, и Revert есть что снимать: отмечается до
	// вызовов, так что снимается и поставленное наполовину (SetLinkDNS
	// прошёл, SetLinkDomains — нет).
	applied bool
}

// DetectSystemDNS узнаёт, кто ведёт /etc/resolv.conf, и способ, которым
// csqtt-cli задаст DNS туннеля адаптеру name. Ничего не меняет. Ссылка на чужой
// генератор — ошибка: перезаписать файл значило бы сломать его хозяину
// resolv.conf до выхода csqtt-cli.
func DetectSystemDNS(name string) (*SystemDNS, error) {
	method, resolvconf, err := detectDNSMethod()
	if err != nil {
		return nil, err
	}
	s := &SystemDNS{method: method, name: name, resolvconf: resolvconf}
	if method == DNSFile {
		if b, err := os.ReadFile(resolvConfPath()); err == nil {
			if gen := fileGenerator(b); gen != "" {
				s.warning = fmt.Sprintf("resolv.conf пишет %s: если он перепишет файл (смена сети, продление DHCP), "+
					"DNS туннеля пропадёт до переподключения csqtt-cli", gen)
			}
		}
	}
	return s, nil
}

// fileGenerator — кто написал resolv.conf, по заголовку «# Generated by …»;
// "" — неизвестно или docker (после правки файл он не трогает).
func fileGenerator(conf []byte) string {
	line := firstLine(string(conf))
	gen, ok := strings.CutPrefix(line, "# Generated by ")
	if !ok || strings.HasPrefix(gen, "Docker") {
		return ""
	}
	return strings.TrimRight(gen, ". ")
}

func detectDNSMethod() (DNSMethod, string, error) {
	path := resolvConfPath()
	fi, err := os.Lstat(path)
	if errors.Is(err, fs.ErrNotExist) {
		return DNSFile, "", nil
	}
	if err != nil {
		return 0, "", fmt.Errorf("resolv.conf: %w", err)
	}

	if fi.Mode()&fs.ModeSymlink == 0 {
		b, err := os.ReadFile(path)
		if err != nil {
			return 0, "", fmt.Errorf("resolv.conf: %w", err)
		}
		switch {
		case hasNameserver(b, resolvedStub):
			// Копия заглушки без ссылки — тоже systemd-resolved.
			return resolvedMethod()
		case bytes.Contains(b, []byte(resolvconfHeader)):
			return resolvconfMethod()
		}
		return DNSFile, "", nil
	}

	target, err := filepath.EvalSymlinks(path)
	if err != nil {
		return 0, "", fmt.Errorf("resolv.conf — ссылка, которая никуда не ведёт: %w", err)
	}
	run := runRoot
	if r, err := filepath.EvalSymlinks(runRoot); err == nil {
		run = r
	}
	switch {
	case under(target, filepath.Join(run, "systemd/resolve")):
		return resolvedMethod()
	case under(target, filepath.Join(run, "resolvconf")):
		return resolvconfMethod()
	default:
		return 0, "", fmt.Errorf("/etc/resolv.conf — ссылка на %s: этот генератор csqtt-cli не знает "+
			"(умеет systemd-resolved, resolvconf и обычный файл) и задать DNS туннеля не может", target)
	}
}

// resolvedMethod — systemd-resolved, если служба отвечает по D-Bus.
func resolvedMethod() (DNSMethod, string, error) {
	bus, err := dialResolved()
	if err == nil {
		err = bus.call(context.Background(), "org.freedesktop.DBus.Peer.Ping")
		bus.close()
	}
	if err != nil {
		return 0, "", fmt.Errorf("resolv.conf ведёт на systemd-resolved, а служба не отвечает: %w", err)
	}
	return DNSResolved, "", nil
}

// resolvconfMethod — Debian resolvconf или openresolv: их различает --version.
func resolvconfMethod() (DNSMethod, string, error) {
	prog, err := findResolvconf()
	if err != nil {
		return 0, "", err
	}
	out, err := runCommand(nil, prog, "--version")
	if err != nil {
		return 0, "", fmt.Errorf("resolvconf --version: %w", err)
	}
	switch v := string(out); {
	case strings.Contains(v, "Debian resolvconf"):
		return DNSResolvconfDebian, prog, nil
	case strings.Contains(v, "openresolv"):
		return DNSOpenresolv, prog, nil
	default:
		return 0, "", fmt.Errorf("resolv.conf ведёт resolvconf, а %s — незнакомый (%q)", prog, firstLine(v))
	}
}

// findResolvconf — программа resolvconf: под sudo PATH обычно с sbin, но
// не всегда.
func findResolvconf() (string, error) {
	for _, p := range resolvconfPaths {
		if fi, err := os.Stat(p); err == nil && !fi.IsDir() {
			return p, nil
		}
	}
	if p, err := exec.LookPath("resolvconf"); err == nil {
		return p, nil
	}
	return "", errors.New("resolv.conf ведёт resolvconf, а программы resolvconf нет")
}

// resolvconfPaths — где искать resolvconf до PATH; подменяется в тестах.
var resolvconfPaths = []string{"/usr/sbin/resolvconf", "/sbin/resolvconf"}

// Applied — звали ли Set после последнего Revert: поставленное, хотя бы
// отчасти, ещё не снято.
func (s *SystemDNS) Applied() bool { return s.applied }

// Warning — чем выбранный способ ненадёжен; "" — ничем.
func (s *SystemDNS) Warning() string { return s.warning }

// Method — выбранный способ.
func (s *SystemDNS) Method() DNSMethod { return s.method }

// String — способ для строки вывода.
func (s *SystemDNS) String() string {
	switch s.method {
	case DNSResolvconfDebian, DNSOpenresolv:
		return fmt.Sprintf("%s, запись %s", s.method, s.record())
	case DNSResolved:
		return fmt.Sprintf("%s, линк %s", s.method, s.name)
	case DNSFile:
		return fmt.Sprintf("%s, прежний — в %s", s.method, backupPath())
	}
	return s.method.String()
}

// record — имя записи resolvconf.
func (s *SystemDNS) record() string { return "tun." + s.name }

// Recover убирает то, что оставил упавший прошлый запуск: запись resolvconf
// и перезаписанный resolv.conf. Звать до Set и только когда второго csqtt-cli на
// машине быть не может (после блокировки адаптера) — иначе снялся бы DNS
// работающего. Возвращает, что убрано; "" — ничего.
func (s *SystemDNS) Recover() (string, error) {
	switch s.method {
	case DNSResolvconfDebian, DNSOpenresolv:
		if !s.recordExists() {
			return "", nil
		}
		if err := s.deleteRecord(); err != nil {
			return "", fmt.Errorf("запись %s прошлого запуска: %w", s.record(), err)
		}
		return fmt.Sprintf("запись %s прошлого запуска csqtt-cli снята", s.record()), nil
	case DNSFile:
		return restoreFile()
	}
	// systemd-resolved: настройки линка ушли вместе с ним.
	return "", nil
}

// recordExists — есть ли запись resolvconf (Debian держит их в interface,
// openresolv — в interfaces).
func (s *SystemDNS) recordExists() bool {
	for _, dir := range []string{"interface", "interfaces"} {
		if _, err := os.Stat(filepath.Join(runRoot, "resolvconf", dir, s.record())); err == nil {
			return true
		}
	}
	return false
}

// Set делает servers DNS системы; повторный вызов заменяет прежние. index —
// индекс интерфейса адаптера (для systemd-resolved). Пустой servers снимает
// поставленное: сервер DNS не выдал, остаётся DNS системы.
//
// После отказа Revert всё равно снимает то, что успело встать: каждый способ
// снимает и несделанное без вреда (RevertLink, resolvconf -d, возврат
// копии, которой нет).
func (s *SystemDNS) Set(index int, servers []netip.Addr) error {
	if len(servers) == 0 {
		return s.Revert(index)
	}
	s.applied = true
	var err error
	switch s.method {
	case DNSResolved:
		err = setResolved(index, servers)
	case DNSResolvconfDebian:
		_, err = runCommand(resolvconfInput(servers), s.resolvconf, "-a", s.record())
	case DNSOpenresolv:
		_, err = runCommand(resolvconfInput(servers), s.resolvconf, "-a", s.record(), "-m", "0", "-x")
	case DNSFile:
		err = writeResolvConf(servers)
	default:
		err = fmt.Errorf("неизвестный способ %v", s.method)
	}
	if err != nil {
		return fmt.Errorf("DNS системы (%s): %w", s.method, err)
	}
	return nil
}

// Revert снимает то, что поставил Set; без Set ничего не делает.
// Повторный вызов безвреден.
func (s *SystemDNS) Revert(index int) error {
	if !s.applied {
		return nil
	}
	var err error
	switch s.method {
	case DNSResolved:
		err = revertResolved(index)
	case DNSResolvconfDebian, DNSOpenresolv:
		err = s.deleteRecord()
	case DNSFile:
		_, err = restoreFile()
	}
	if err != nil {
		return fmt.Errorf("DNS системы (%s): %w", s.method, err)
	}
	s.applied = false
	return nil
}

func (s *SystemDNS) deleteRecord() error {
	args := []string{"-d", s.record()}
	if s.method == DNSOpenresolv {
		// Без -f openresolv ругается на отсутствующую запись; Debian -f
		// не знает, а отсутствующую молча пропускает.
		args = []string{"-f", "-d", s.record()}
	}
	_, err := runCommand(nil, s.resolvconf, args...)
	return err
}

// resolvconfInput — запись resolvconf: только серверы. search и options
// остаются от других записей.
func resolvconfInput(servers []netip.Addr) []byte {
	var b bytes.Buffer
	for _, a := range servers {
		fmt.Fprintf(&b, "nameserver %s\n", a.Unmap())
	}
	return b.Bytes()
}

// runCommand запускает программу и возвращает её вывод; в ошибке — вывод
// ошибок программы.
var runCommand = func(stdin []byte, prog string, args ...string) ([]byte, error) {
	ctx, cancel := context.WithTimeout(context.Background(), commandTimeout)
	defer cancel()
	cmd := exec.CommandContext(ctx, prog, args...)
	if stdin != nil {
		cmd.Stdin = bytes.NewReader(stdin)
	}
	var stderr bytes.Buffer
	cmd.Stderr = &stderr
	out, err := cmd.Output()
	if err != nil {
		if msg := strings.TrimSpace(stderr.String()); msg != "" {
			return out, fmt.Errorf("%s %s: %w: %s", filepath.Base(prog), strings.Join(args, " "), err, msg)
		}
		return out, fmt.Errorf("%s %s: %w", filepath.Base(prog), strings.Join(args, " "), err)
	}
	return out, nil
}

// commandTimeout — resolvconf ждёт свою блокировку до 10 с.
const commandTimeout = 20 * time.Second

// ──────────────────────────── systemd-resolved ────────────────────────────

// resolvedBus — вызовы systemd-resolved; интерфейс ради тестов.
type resolvedBus interface {
	// call зовёт метод org.freedesktop.resolve1 на /org/freedesktop/resolve1;
	// имя без интерфейса — метод Manager.
	call(ctx context.Context, method string, args ...any) error
	close()
}

// dialResolved — соединение с системной шиной; подменяется в тестах.
var dialResolved = func() (resolvedBus, error) {
	conn, err := dbus.ConnectSystemBus()
	if err != nil {
		return nil, fmt.Errorf("системная шина D-Bus: %w", err)
	}
	return dbusResolved{conn: conn}, nil
}

type dbusResolved struct{ conn *dbus.Conn }

func (b dbusResolved) call(ctx context.Context, method string, args ...any) error {
	if !strings.Contains(method, ".") {
		method = "org.freedesktop.resolve1.Manager." + method
	}
	obj := b.conn.Object("org.freedesktop.resolve1", "/org/freedesktop/resolve1")
	return obj.CallWithContext(ctx, method, 0, args...).Err
}

func (b dbusResolved) close() { b.conn.Close() }

// resolvedTimeout — на один вызов systemd-resolved.
const resolvedTimeout = 10 * time.Second

// resolvedAddr — адрес в SetLinkDNS: a(iay).
type resolvedAddr struct {
	Family  int32
	Address []byte
}

// resolvedDomain — домен в SetLinkDomains: a(sb).
type resolvedDomain struct {
	Domain      string
	RoutingOnly bool
}

// setResolved ставит линку DNS, маршрутный домен «~.» (все имена — сюда,
// кроме более точных доменов других линков) и DefaultRoute.
func setResolved(index int, servers []netip.Addr) error {
	addrs := make([]resolvedAddr, 0, len(servers))
	for _, a := range servers {
		a = a.Unmap()
		family := int32(unix.AF_INET)
		if a.Is6() {
			family = unix.AF_INET6
		}
		addrs = append(addrs, resolvedAddr{Family: family, Address: a.AsSlice()})
	}
	return withResolved(func(ctx context.Context, bus resolvedBus) error {
		if err := bus.call(ctx, "SetLinkDNS", int32(index), addrs); err != nil {
			return fmt.Errorf("SetLinkDNS: %w", err)
		}
		if err := bus.call(ctx, "SetLinkDomains", int32(index), []resolvedDomain{{".", true}}); err != nil {
			return fmt.Errorf("SetLinkDomains: %w", err)
		}
		// SetLinkDefaultRoute — с systemd 240; старшим хватает «~.».
		if err := bus.call(ctx, "SetLinkDefaultRoute", int32(index), true); err != nil && !dbusErrorIs(err, "org.freedesktop.DBus.Error.UnknownMethod") {
			return fmt.Errorf("SetLinkDefaultRoute: %w", err)
		}
		return nil
	})
}

// revertResolved снимает настройки линка. Линка уже нет — снимать нечего.
func revertResolved(index int) error {
	return withResolved(func(ctx context.Context, bus resolvedBus) error {
		err := bus.call(ctx, "RevertLink", int32(index))
		if err != nil && !dbusErrorIs(err, "org.freedesktop.resolve1.NoSuchLink") {
			return fmt.Errorf("RevertLink: %w", err)
		}
		return nil
	})
}

func withResolved(f func(context.Context, resolvedBus) error) error {
	bus, err := dialResolved()
	if err != nil {
		return err
	}
	defer bus.close()
	ctx, cancel := context.WithTimeout(context.Background(), resolvedTimeout)
	defer cancel()
	return f(ctx, bus)
}

func dbusErrorIs(err error, name string) bool {
	var derr dbus.Error
	if errors.As(err, &derr) {
		return derr.Name == name
	}
	var perr *dbus.Error
	return errors.As(err, &perr) && perr.Name == name
}

// ──────────────────────────── перезапись ────────────────────────────

func resolvConfPath() string { return filepath.Join(etcRoot, "resolv.conf") }

func backupPath() string { return resolvConfPath() + backupSuffix }

// writeResolvConf пишет свой resolv.conf; прежний, если копии ещё нет, сначала
// уходит в копию. Копия есть — значит, файл уже наш (Set повторно).
func writeResolvConf(servers []netip.Addr) error {
	path := resolvConfPath()
	old, err := os.ReadFile(path)
	if err != nil && !errors.Is(err, fs.ErrNotExist) {
		return err
	}
	if _, err := os.Stat(backupPath()); errors.Is(err, fs.ErrNotExist) {
		if bytes.HasPrefix(old, []byte(fileMarker)) {
			// Свой файл без копии — его копию кто-то удалил; прежнего не
			// вернуть, но и копировать свой как прежний нельзя.
			return fmt.Errorf("%s написал csqtt-cli, а копии прежнего (%s) нет", path, backupPath())
		}
		if err := replaceFile(backupPath(), old); err != nil {
			return fmt.Errorf("копия resolv.conf: %w", err)
		}
	} else if err != nil {
		return err
	}
	return replaceFile(path, fileContent(servers, old))
}

// fileContent — свой resolv.conf: метка, серверы туннеля и из прежнего —
// search, domain и options (короткие имена и настройки резолвера те же).
func fileContent(servers []netip.Addr, old []byte) []byte {
	var b bytes.Buffer
	fmt.Fprintf(&b, "%s; прежний файл — %s, csqtt-cli вернёт его при выходе\n", fileMarker, filepath.Base(backupPath()))
	for _, a := range servers {
		fmt.Fprintf(&b, "nameserver %s\n", a.Unmap())
	}
	for _, line := range strings.Split(string(old), "\n") {
		f := strings.Fields(line)
		if len(f) > 0 && (f[0] == "search" || f[0] == "domain" || f[0] == "options") {
			b.WriteString(strings.TrimSpace(line) + "\n")
		}
	}
	return b.Bytes()
}

// restoreFile возвращает прежний resolv.conf из копии. Файл уже не наш —
// его записал кто-то после (DHCP, NetworkManager): он и остаётся, копия
// удаляется. Возвращает, что сделано; "" — копии не было.
func restoreFile() (string, error) {
	backup, err := os.ReadFile(backupPath())
	if errors.Is(err, fs.ErrNotExist) {
		return "", nil
	}
	if err != nil {
		return "", fmt.Errorf("копия resolv.conf: %w", err)
	}
	cur, err := os.ReadFile(resolvConfPath())
	if err != nil && !errors.Is(err, fs.ErrNotExist) {
		return "", err
	}
	done := "прежний resolv.conf возвращён из " + backupPath()
	if bytes.HasPrefix(cur, []byte(fileMarker)) {
		if err := replaceFile(resolvConfPath(), backup); err != nil {
			return "", fmt.Errorf("возврат resolv.conf: %w", err)
		}
	} else {
		done = "resolv.conf после csqtt-cli переписал кто-то другой — он и остаётся, копия " + backupPath() + " удалена"
	}
	if err := os.Remove(backupPath()); err != nil {
		return "", err
	}
	return done, nil
}

// replaceFile заменяет файл целиком: новый рядом и rename, чтобы читатель
// не застал половину. В контейнере resolv.conf смонтирован отдельно, и
// rename поверх точки монтирования — EBUSY: тогда запись на месте.
// Права прежнего файла сохраняются.
func replaceFile(path string, data []byte) error {
	mode := fs.FileMode(0o644)
	if fi, err := os.Stat(path); err == nil {
		mode = fi.Mode().Perm()
	}
	tmp, err := os.CreateTemp(filepath.Dir(path), "."+filepath.Base(path)+"."+app.Name+"-*")
	if err != nil {
		return err
	}
	_, err = tmp.Write(data)
	if err == nil {
		err = tmp.Chmod(mode)
	}
	if err == nil {
		err = tmp.Sync()
	}
	if cerr := tmp.Close(); err == nil {
		err = cerr
	}
	if err == nil {
		err = os.Rename(tmp.Name(), path)
		if err == nil {
			return nil
		}
	}
	os.Remove(tmp.Name())
	if !errors.Is(err, syscall.EBUSY) {
		return err
	}
	return os.WriteFile(path, data, mode)
}

